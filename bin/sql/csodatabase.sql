CREATE TABLE IF NOT EXISTS users (
	userID INT UNSIGNED NOT NULL AUTO_INCREMENT,
	userName VARCHAR(16) NOT NULL,
	password BINARY(60) NOT NULL,
	registerTime DATETIME NOT NULL,
	PRIMARY KEY (userID),
	UNIQUE KEY uk_userName (userName)
);

CREATE TABLE IF NOT EXISTS user_characters (
	userID INT UNSIGNED NOT NULL,
	unk1 TINYINT UNSIGNED DEFAULT 0,
	nickName VARBINARY(16) NOT NULL,
	unk4_1 VARBINARY(16) DEFAULT (''),
	unk4_2 TINYINT UNSIGNED DEFAULT 0,
	unk4_3 TINYINT UNSIGNED DEFAULT 0,
	unk4_4 TINYINT UNSIGNED DEFAULT 0,
	level TINYINT UNSIGNED DEFAULT 1,
	unk10 TINYINT UNSIGNED DEFAULT 0,
	exp BIGINT UNSIGNED DEFAULT 0,
	cash BIGINT UNSIGNED DEFAULT 0,
	points BIGINT UNSIGNED DEFAULT 0,
	battles INT UNSIGNED DEFAULT 0,
	wins INT UNSIGNED DEFAULT 0,
	frags INT UNSIGNED DEFAULT 0,
	deaths INT UNSIGNED DEFAULT 0,
	city SMALLINT UNSIGNED DEFAULT 0,
	county SMALLINT UNSIGNED DEFAULT 0,
	neighborhood SMALLINT UNSIGNED DEFAULT 0,
	unk200_5 VARBINARY(64) DEFAULT (''),
	unk400 INT UNSIGNED DEFAULT 0,
	unk800 TINYINT UNSIGNED DEFAULT 0,
	clanID INT UNSIGNED DEFAULT 0,
	clanMarkID INT UNSIGNED DEFAULT 0,
	clanName VARBINARY(32) DEFAULT (''),
	clanUnk4 TINYINT DEFAULT 0,
	clanUnk5 TINYINT DEFAULT 0,
	clanUnk6 TINYINT DEFAULT 0,
	prefixID SMALLINT UNSIGNED NOT NULL DEFAULT 0,
	honorPoints SMALLINT UNSIGNED NOT NULL DEFAULT 0,
	badge0 TINYINT UNSIGNED NOT NULL DEFAULT 0,
	badge1 TINYINT UNSIGNED NOT NULL DEFAULT 0,
	badge2 TINYINT UNSIGNED NOT NULL DEFAULT 0,
	badge3 TINYINT UNSIGNED NOT NULL DEFAULT 0,
	badge4 TINYINT UNSIGNED NOT NULL DEFAULT 0,
	PRIMARY KEY (userID),
	UNIQUE KEY uk_nickName (nickName),
	FOREIGN KEY (userID) REFERENCES users(userID) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS user_options (
	userID INT UNSIGNED NOT NULL,
	userOption BLOB NOT NULL,
	PRIMARY KEY (userID),
	FOREIGN KEY (userID) REFERENCES users(userID) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS user_buymenus (
	userBuyMenuID INT UNSIGNED NOT NULL AUTO_INCREMENT,
	userID INT UNSIGNED NOT NULL,
	categoryID TINYINT UNSIGNED,
	slot1 SMALLINT UNSIGNED,
	slot2 SMALLINT UNSIGNED,
	slot3 SMALLINT UNSIGNED,
	slot4 SMALLINT UNSIGNED,
	slot5 SMALLINT UNSIGNED,
	slot6 SMALLINT UNSIGNED,
	slot7 SMALLINT UNSIGNED,
	slot8 SMALLINT UNSIGNED,
	slot9 SMALLINT UNSIGNED,
	PRIMARY KEY (userBuyMenuID),
	UNIQUE KEY uk_user_category (userID, categoryID),
	FOREIGN KEY (userID) REFERENCES users(userID) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS user_bookmarks (
	userBookMarkID INT UNSIGNED NOT NULL AUTO_INCREMENT,
	userID INT UNSIGNED NOT NULL,
	slotID TINYINT UNSIGNED NOT NULL,
	name VARBINARY(32) NOT NULL DEFAULT '',
	primaryItemID SMALLINT UNSIGNED NOT NULL DEFAULT 0,
	primaryAmmo SMALLINT UNSIGNED NOT NULL DEFAULT 0,
	secondaryItemID SMALLINT UNSIGNED NOT NULL DEFAULT 0,
	secondaryAmmo SMALLINT UNSIGNED NOT NULL DEFAULT 0,
	flashbang SMALLINT UNSIGNED NOT NULL DEFAULT 0,
	hegrenade SMALLINT UNSIGNED NOT NULL DEFAULT 0,
	smokegrenade SMALLINT UNSIGNED NOT NULL DEFAULT 0,
	defusekit SMALLINT UNSIGNED NOT NULL DEFAULT 0,
	nightvision SMALLINT UNSIGNED NOT NULL DEFAULT 0,
	kevlar SMALLINT UNSIGNED NOT NULL DEFAULT 0,
	unk1 SMALLINT UNSIGNED NOT NULL DEFAULT 0,
	PRIMARY KEY (userBookMarkID),
	UNIQUE KEY uk_user_slot (userID, slotID),
	KEY idx_userID (userID),
	FOREIGN KEY (userID) REFERENCES users(userID) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS user_inventory (
	userInventoryID INT UNSIGNED NOT NULL AUTO_INCREMENT,
	userID INT UNSIGNED NOT NULL,
	slotID SMALLINT UNSIGNED NOT NULL,
	itemID SMALLINT UNSIGNED NOT NULL,
	count SMALLINT UNSIGNED NOT NULL DEFAULT 1,
	activeFlag TINYINT UNSIGNED NOT NULL DEFAULT 1,
	inUse BOOL DEFAULT 0,
	obtainTime INT UNSIGNED DEFAULT 0,
	expirationTime INT UNSIGNED DEFAULT 0,
	enhanceBits INT UNSIGNED NOT NULL DEFAULT 0,
	PRIMARY KEY (userInventoryID),
	KEY idx_userID (userID),
	KEY idx_user_expire (userID, expirationTime),
	FOREIGN KEY (userID) REFERENCES users(userID) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS user_sessions (
	userID INT UNSIGNED NOT NULL,
	serverID TINYINT UNSIGNED NOT NULL,
	channelID TINYINT UNSIGNED NOT NULL,
	PRIMARY KEY (userID),
	FOREIGN KEY (userID) REFERENCES users(userID) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS user_transfers (
	userID INT UNSIGNED NOT NULL,
	authToken BINARY(29) NOT NULL,
	serverID TINYINT UNSIGNED NOT NULL,
	channelID TINYINT UNSIGNED NOT NULL,
	transferTime BIGINT UNSIGNED NOT NULL,
	PRIMARY KEY (userID),
	FOREIGN KEY (userID) REFERENCES users(userID) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS user_titles (
	id INT UNSIGNED NOT NULL AUTO_INCREMENT,
	userID INT UNSIGNED NOT NULL,
	titleID SMALLINT UNSIGNED NOT NULL,
	unlockTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
	PRIMARY KEY (id),
	UNIQUE KEY uk_user_title (userID, titleID),
	KEY idx_userID (userID),
	FOREIGN KEY (userID) REFERENCES users(userID) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS user_attendance (
	userID INT UNSIGNED NOT NULL,
	consecutiveDays TINYINT UNSIGNED NOT NULL DEFAULT 0,
	totalCheckIns INT UNSIGNED NOT NULL DEFAULT 0,
	lastCheckInDate DATE DEFAULT NULL,
	createdTime DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
	updatedTime DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
	PRIMARY KEY (userID),
	FOREIGN KEY (userID) REFERENCES users(userID) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS user_bingo (
	userID INT UNSIGNED NOT NULL,
	status INT NOT NULL DEFAULT 0,
	canPlay TINYINT(1) NOT NULL DEFAULT 1,
	PRIMARY KEY (userID),
	FOREIGN KEY (userID) REFERENCES users(userID) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS user_bingo_slots (
	userID INT UNSIGNED NOT NULL,
	slotIdx TINYINT UNSIGNED NOT NULL,
	number TINYINT UNSIGNED NOT NULL,
	opened TINYINT UNSIGNED NOT NULL DEFAULT 0,
	PRIMARY KEY (userID, slotIdx),
	FOREIGN KEY (userID) REFERENCES users(userID) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS user_bingo_prizes (
	userID INT UNSIGNED NOT NULL,
	lineIdx TINYINT UNSIGNED NOT NULL,
	itemID INT UNSIGNED NOT NULL,
	count SMALLINT UNSIGNED NOT NULL DEFAULT 1,
	duration INT UNSIGNED NOT NULL DEFAULT 0,
	opened TINYINT UNSIGNED NOT NULL DEFAULT 0,
	PRIMARY KEY (userID, lineIdx),
	FOREIGN KEY (userID) REFERENCES users(userID) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS user_quests (
	id INT UNSIGNED NOT NULL AUTO_INCREMENT,
	userID INT UNSIGNED NOT NULL,
	questID INT UNSIGNED NOT NULL,
	state TINYINT UNSIGNED NOT NULL DEFAULT 0,
	count0 SMALLINT UNSIGNED NOT NULL DEFAULT 0,
	count1 SMALLINT UNSIGNED NOT NULL DEFAULT 0,
	count2 SMALLINT UNSIGNED NOT NULL DEFAULT 0,
	count3 SMALLINT UNSIGNED NOT NULL DEFAULT 0,
	count4 SMALLINT UNSIGNED NOT NULL DEFAULT 0,
	count5 SMALLINT UNSIGNED NOT NULL DEFAULT 0,
	lastUpdatedDate DATE NOT NULL DEFAULT (CURDATE()),
	isTracked TINYINT UNSIGNED NOT NULL DEFAULT 0,
	PRIMARY KEY (id),
	UNIQUE KEY uk_user_quest (userID, questID),
	KEY idx_userID (userID),
	FOREIGN KEY (userID) REFERENCES users(userID) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS user_quest_stats (
	userID INT UNSIGNED NOT NULL,
	specialStreak SMALLINT UNSIGNED NOT NULL DEFAULT 0,
	specialMaxStreak SMALLINT UNSIGNED NOT NULL DEFAULT 0,
	maxDailyCompleted TINYINT UNSIGNED NOT NULL DEFAULT 0,
	allClearCount SMALLINT UNSIGNED NOT NULL DEFAULT 0,
	lastSpecialDate DATE DEFAULT NULL,
	lastAllClearDate DATE DEFAULT NULL,
	PRIMARY KEY (userID),
	FOREIGN KEY (userID) REFERENCES users(userID) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS user_itemsets (
	userID INT UNSIGNED NOT NULL,
	slotID TINYINT UNSIGNED NOT NULL,
	itemID SMALLINT UNSIGNED NOT NULL,
	PRIMARY KEY (userID, slotID),
	FOREIGN KEY (userID) REFERENCES users(userID) ON DELETE CASCADE
);
